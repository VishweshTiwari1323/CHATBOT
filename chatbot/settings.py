    db_path = Path('/tmp/db.sqlite3')
    local_db = BASE_DIR / 'db.sqlite3'
    if not db_path.exists() and local_db.exists():
        shutil.copyfile(local_db, db_path)
    
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': db_path,
        }
    }
